func TestGeneratedSignalHeaderWindow(t *testing.T) {
	marker := "// generated by tool — do not edit\n"
	// Marker on line 10 is inside the window; on line 11 it is not.
	tenLines := strings.Repeat("// filler\n", 9) + marker
	if got := intel.GeneratedSignal("src/file.ts", []byte(tenLines)); got != intel.SignalHeader {
		t.Errorf("marker on line 10 = %q, want %q", got, intel.SignalHeader)
	}
	elevenLines := strings.Repeat("// filler\n", 10) + marker
	if got := intel.GeneratedSignal("src/file.ts", []byte(elevenLines)); got != "" {
		t.Errorf("marker on line 11 = %q, want empty", got)
	}
	// A marker starting past byte 1024 is outside the window even on line 2.
	// The trailing NUL suppresses the minified rule, which the long filler
	// line would otherwise trip, so only the header window decides.
	longFirstLine := "// " + strings.Repeat("x", 1021) + "\n" + marker + "\x00"
	if len(longFirstLine) <= 1024 {
		t.Fatalf("fixture too short: %d bytes", len(longFirstLine))
	}
	if got := intel.GeneratedSignal("src/file.ts", []byte(longFirstLine)); got != "" {
		t.Errorf("marker past byte 1024 = %q, want empty", got)
	}
	// Without the NUL the same body matches the minified rule instead: the
	// byte window is no coverage hole for a long-line file.
	plain := strings.TrimRight(longFirstLine, "\x00")
	if got := intel.GeneratedSignal("src/file.ts", []byte(plain)); got != intel.SignalMinified {
		t.Errorf("marker past byte 1024 without NUL = %q, want %q", got, intel.SignalMinified)
	}
	// The two phrases split across the byte boundary do not match either.
	splitPhrases := "// generated " + strings.Repeat("x", 1012) + "\n// do not edit\n\x00"
	if len(splitPhrases) <= 1024 {
		t.Fatalf("fixture too short: %d bytes", len(splitPhrases))
	}
	if got := intel.GeneratedSignal("src/file.ts", []byte(splitPhrases)); got != "" {
		t.Errorf("phrases split across byte 1024 = %q, want empty", got)
	}
}

func TestGeneratedSignalMinifiedBoundaries(t *testing.T) {
	line110 := strings.Repeat("a", 110)
	line111 := strings.Repeat("a", 111)
	cases := []struct {
		name string
		path string
		body string
		want string
	}{
		{"empty body", "src/x.js", "", ""},
		{"no newline 110", "src/x.js", line110, ""},
		{"no newline 111", "src/x.js", line111, intel.SignalMinified},
		{"two lines averaging 110", "src/x.js", line110 + "\n" + strings.Repeat("b", 109), ""},
		{"two lines averaging 111", "src/x.js", line111 + "\n" + strings.Repeat("b", 110), intel.SignalMinified},
		{"trailing newline dilutes", "src/x.js", line111 + "\n", ""},
		{"ts extension", "src/webAssets.ts", line111, intel.SignalMinified},
		{"json extension", "data/openapi.json", line111, intel.SignalMinified},
		{"ordinary source", "src/x.go", "package x\n\nfunc A() {}\n", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := intel.GeneratedSignal(c.path, []byte(c.body)); got != c.want {
				t.Errorf("GeneratedSignal(%q) = %q, want %q", c.path, got, c.want)
			}
		})
	}
}

func TestGeneratedSignalBinaryBodies(t *testing.T) {
	longLine := strings.Repeat("a", 200)
	binary := []byte(longLine + "\n\x00" + longLine)
	if got := intel.GeneratedSignal("src/blob.dat", binary); got != "" {
		t.Errorf("binary long-line body = %q, want empty (minified suppressed)", got)
	}
	// A binary body may still match a name or header rule.
	if got := intel.GeneratedSignal("yarn.lock", binary); got != intel.SignalLockfile {
		t.Errorf("binary lockfile = %q, want %q", got, intel.SignalLockfile)
	}
	headerBinary := []byte("// @generated\n\x00" + longLine)
	if got := intel.GeneratedSignal("src/blob.ts", headerBinary); got != intel.SignalHeader {
		t.Errorf("binary header body = %q, want %q", got, intel.SignalHeader)
	}
}

// TestRequiredFilesRecordsGeneratedSignals proves discovery records the signal
// from the evidence bytes at ContentRevision: the base for a deletion, the
// head otherwise.
func TestRequiredFilesRecordsGeneratedSignals(t *testing.T) {
	base, head := stubRevisions(t)
	changes := []core.FileChange{
		{Path: "web/yarn.lock", OldPath: "web/yarn.lock", Kind: core.ChangeDeleted},
		{Path: "src/webAssets.ts", Kind: core.ChangeModified},
		{Path: "src/plain.ts", Kind: core.ChangeModified},
	}
	reader := stubReader{bodies: map[string]map[string]oracleCase{
		stubBaseSHA: {
			"web/yarn.lock": {Path: "web/yarn.lock", Body: "# yarn lockfile v1\n", Available: true},
		},
		stubHeadSHA: {
			"src/webAssets.ts": {Path: "src/webAssets.ts", Body: "// generated by scripts/build-embed.mjs — do not edit\n", Available: true},
			"src/plain.ts":     {Path: "src/plain.ts", Body: "export const x = 1\n", Available: true},
		},
	}}
	scope, err := intel.RequiredFiles(context.Background(), changes, reader, base, head, nil)
	if err != nil {
		t.Fatalf("RequiredFiles: %v", err)
	}
	want := map[string]string{
		"web/yarn.lock":    intel.SignalLockfile,
		"src/webAssets.ts": intel.SignalHeader,
		"src/plain.ts":     "",
	}
	if len(scope.Required) != len(want) {
		t.Fatalf("required holds %d units, want %d", len(scope.Required), len(want))
	}
	for _, unit := range scope.Required {
		if unit.Generated != want[unit.Path] {
			t.Errorf("unit %q Generated = %q, want %q", unit.Path, unit.Generated, want[unit.Path])
		}
	}
}

// TestRequiredFilesLeavesUnreadableBodyUnsigned proves an unreadable body
// stays required without a content-based signal.
func TestRequiredFilesLeavesUnreadableBodyUnsigned(t *testing.T) {
	base, head := stubRevisions(t)
	changes := []core.FileChange{{Path: "src/locked.go", Kind: core.ChangeModified}}
	scope, err := intel.RequiredFiles(context.Background(), changes, failingReader{}, base, head, nil)
	if err != nil {
		t.Fatalf("RequiredFiles: %v", err)
	}
	if len(scope.Required) != 1 {
		t.Fatalf("required holds %d units, want 1", len(scope.Required))
	}
	unit := scope.Required[0]
	if unit.Available {
		t.Error("unreadable unit reports available")
	}
	if unit.Generated != "" {
		t.Errorf("unreadable unit Generated = %q, want empty", unit.Generated)
	}
}
