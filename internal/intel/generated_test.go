func TestGeneratedSignalNameRulesBeatContentRules(t *testing.T) {
	header := []byte("// @generated by tool\n")
	if got := intel.GeneratedSignal("yarn.lock", header); got != intel.SignalLockfile {
		t.Errorf("lockfile with header = %q, want %q", got, intel.SignalLockfile)
	}
	if got := intel.GeneratedSignal("app.min.js", header); got != intel.SignalBundleName {
		t.Errorf("bundle name with header = %q, want %q", got, intel.SignalBundleName)
	}
	headerBeatsMinified := []byte("// @generated\n" + strings.Repeat("a", 200))
	if got := intel.GeneratedSignal("src/blob.ts", headerBeatsMinified); got != intel.SignalHeader {
		t.Errorf("header with minified body = %q, want %q", got, intel.SignalHeader)
	}
}

