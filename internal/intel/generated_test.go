// The header excerpt quotes the matched marker line for the PR warning. It
// is derived from the same bounded window the detector read, sanitized of
// backticks and control bytes, and capped at 120 bytes with an ellipsis — a
// marker can sit on a minified line of any length.
func TestHeaderExcerpt(t *testing.T) {
	t.Run("the marker line itself", func(t *testing.T) {
		body := "// generated by scripts/build-embed.mjs — do not edit\n" + strings.Repeat("a", 1000) + "\n"
		if got := intel.HeaderExcerpt([]byte(body)); got != "// generated by scripts/build-embed.mjs — do not edit" {
			t.Errorf("excerpt = %q", got)
		}
	})

	t.Run("a 300 KB line with backticks is sanitized and capped", func(t *testing.T) {
		line := "// generated by `build-embed` — do not edit " + strings.Repeat("a", 300*1024)
		got := intel.HeaderExcerpt([]byte(line))
		if len(got) > 120 {
			t.Errorf("excerpt is %d bytes, want at most 120", len(got))
		}
		if !strings.HasSuffix(got, "…") {
			t.Errorf("excerpt = %q, want a trailing ellipsis", got)
		}
		if strings.Contains(got, "`") {
			t.Errorf("excerpt kept a backtick: %q", got)
		}
		if !strings.HasPrefix(got, "// generated by build-embed") {
			t.Errorf("excerpt lost the marker text: %q", got)
		}
	})

	t.Run("control bytes are removed", func(t *testing.T) {
		body := "// Code generated by tool. DO NOT EDIT.\x07\x00\npackage x\n"
		got := intel.HeaderExcerpt([]byte(body))
		if got != "// Code generated by tool. DO NOT EDIT." {
			t.Errorf("excerpt = %q, want the control bytes gone", got)
		}
	})

	t.Run("the first marker line wins when the phrases split", func(t *testing.T) {
		body := "package x\n// generated by tool\n\n// do not edit\n"
		if got := intel.HeaderExcerpt([]byte(body)); got != "// generated by tool" {
			t.Errorf("excerpt = %q", got)
		}
	})

	t.Run("no marker no excerpt", func(t *testing.T) {
		if got := intel.HeaderExcerpt([]byte("package x\n")); got != "" {
			t.Errorf("excerpt = %q, want empty", got)
		}
	})

	t.Run("a marker past the window has no excerpt", func(t *testing.T) {
		body := strings.Repeat("// filler\n", 10) + "// generated by tool — do not edit\n"
		if got := intel.HeaderExcerpt([]byte(body)); got != "" {
			t.Errorf("excerpt = %q, want empty", got)
		}
	})
}
